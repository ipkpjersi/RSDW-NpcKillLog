local recentKills = {}   -- killed actor address -> os.clock(), so one death is never counted twice

-- Boss detection from the game's own setup rather than a hand made list
local BOSS_BAR_CLASS = "/Game/Gameplay/AI/Components/BP_BossAiHealthBarComponent.BP_BossAiHealthBarComponent_C"
local MINIBOSS_BASES = {
    "/Game/Gameplay/AI/BaseAIClasses/Characters/BP_AI_Miniboss_Biped_Base.BP_AI_Miniboss_Biped_Base_C",
    "/Game/Gameplay/AI/BaseAIClasses/Characters/BP_AI_Miniboss_Gigantic_Base.BP_AI_Miniboss_Gigantic_Base_C",
}

local function nameSet(list)
    local set = {}
    for part in list:gmatch("[^,]+") do
        local k = lookupKey(trim(part))
        if k ~= "" then set[k] = true end
    end
    return set
end
local extraBosses = nameSet(cfg.ExtraBosses)
local notBosses = nameSet(cfg.NotBosses)

-- Only classes that are already loaded: if the boss bar or a miniboss base is not loaded, the
-- creature that just died cannot be using it, and loading assets inside the death handler is not safe
local function loadedClass(path)
    local c = nil
    pcall(function() c = StaticFindObject(path) end)
    return isValid(c) and c or nil
end

local bossByClass = {}   -- class name -> true/false

local function isBoss(ai, name)
    local k = lookupKey(name)
    if notBosses[k] then return false end
    if extraBosses[k] then return true end
    local okC, className = pcall(function() return ai:GetClass():GetFName():ToString() end)
    className = okC and className or ""
    local cached = bossByClass[className]
    if cached ~= nil then return cached end

    local boss, why = false, nil
    local bar = loadedClass(BOSS_BAR_CLASS)
    if bar then
        local okB, comp = pcall(function() return ai:GetComponentByClass(bar) end)
        if okB and isValid(comp) then boss, why = true, "boss health bar" end
    end
    if not boss then
        for _, path in ipairs(MINIBOSS_BASES) do
            local base = loadedClass(path)
            local okI, isA = false, false
            if base then okI, isA = pcall(function() return ai:IsA(base) end) end
            if okI and isA then boss, why = true, "miniboss base class"; break end
        end
    end
    -- Class name rules, checked against the wiki's boss list (2026-09-28): the vault Rat King and
    -- Plague King (ColossalRat, ColossalFungalRat) have neither a boss bar nor a miniboss base, and
    -- dragon hatchlings have a boss bar but are not bosses
    local lowerClass = className:lower()
    if lowerClass:find("hatchling", 1, true) then boss, why = false, nil
    elseif not boss and (lowerClass:find("boss", 1, true) or lowerClass:find("colossal", 1, true)) then
        boss, why = true, "class name"
    end

    bossByClass[className] = boss
    if boss then log(name .. " counts as a boss (" .. why .. ")") end
    return boss
end

-- Full names of the local player's pawn, newest first. A pawn that dies and respawns is a new
-- object with a new name, so the last few are kept: a creature hit before the respawn and
-- finished after it still has the old pawn in its damage list
local myPawns = {}

local function rememberMyPawn()
    local pc = localController()
    if not pc then return end
    local okP, pawn = pcall(function() return pc:K2_GetPawn() end)
    if not okP or not isValid(pawn) then return end
    local okN, name = pcall(function() return pawn:GetFullName() end)
    if not okN or type(name) ~= "string" or name == "" or name == myPawns[1] then return end
    table.insert(myPawns, 1, name)
    while #myPawns > 3 do table.remove(myPawns) end
end

-- Who damaged this AI, from its controller's ThreatSystem.DamageInstigators.
-- Returns true when the local player did, false when only others did (or nobody, e.g. a fall),
-- nil when the list could not be read; the second value lists the instigators for the log
local function killedByMe(ai)
    rememberMyPawn()
    local ctrl = nil
    pcall(function() ctrl = ai:GetController() end)
    if not isValid(ctrl) then pcall(function() ctrl = ai.Controller end) end
    if not isValid(ctrl) then return nil, "no controller" end
    local okT, threats = pcall(function() return ctrl.ThreatSystem end)
    if not okT or not isValid(threats) then return nil, "no ThreatSystem" end

    local myController = ""
    pcall(function() myController = localController():GetFullName() end)
    local mine = false
    local seen = {}
    local okE = pcall(function()
        threats.DamageInstigators:ForEach(function(_, element)
            local who = element:get()
            if not isValid(who) then return end
            local okN, name = pcall(function() return who:GetFullName() end)
            if not okN or type(name) ~= "string" then return end
            seen[#seen + 1] = name
            if name == myController then mine = true end
            for _, pawnName in ipairs(myPawns) do
                if name == pawnName then mine = true end
            end
        end)
    end)
    if not okE then return nil, "DamageInstigators unreadable" end
    return mine, (#seen > 0 and table.concat(seen, ", ") or "nobody")
end

local warnedUnreadable = false

local function onKill(ai)
    if not isValid(ai) then return end

    local okA, addr = pcall(function() return ai:GetAddress() end)
    local now = os.clock()
    if okA and addr then
        local last = recentKills[addr]
        if last and now - last < 2 then return end
        recentKills[addr] = now
    end

    if cfg.OnlyMyKills then
        local mine, who = killedByMe(ai)
        if mine == false then
            if cfg.LogKills then log("not counted, not your kill: " .. resolveName(ai) .. " (damage by " .. who .. ")") end
            return
        elseif mine == nil and not warnedUnreadable then
            -- Counting it is the safer mistake in single player; say so once
            warnedUnreadable = true
            log("could not tell who killed " .. resolveName(ai) .. " (" .. who .. "), counted anyway; later ones are not logged")
        end
    end

    local name = resolveName(ai)
    ensureCharacter()
    state.kills[name] = (state.kills[name] or 0) + 1
    local message = "Your " .. name .. " kill count is now: " .. formatCount(state.kills[name]) .. "."
    if cfg.LogKills then log(message) end
    local show = cfg.ShowKillMessages
    if isBoss(ai, name) then show = cfg.ShowBossKillMessages end
    -- Shown on a later tick, outside the game's kill handler
    if show then
        ExecuteWithDelay(1, function() ExecuteInGameThread(function() showKillMessage(message) end) end)
    end
    scheduleSave()
    if ui.open then refreshWindow() end

    -- Forget old entries now and then so the table does not grow forever
    for a, t in pairs(recentKills) do
        if now - t > 10 then recentKills[a] = nil end
    end
end

-- The dying creature is the hook's self. The Blueprint class is not loaded until a world is, so
-- registering fails until then; it is retried every 5 s once the player has a pawn, and never
-- registered twice (a hook on a Blueprint function survives a return to the main menu)
local DEATH_HOOK = "/Game/Gameplay/AI/BP_DominionAICharacter.BP_DominionAICharacter_C:BP_OnDeath"
local deathHook = { armed = false, tries = 0 }

local function armDeathHook()
    if deathHook.armed then return end
    local pc = localController()
    local okP, pawn = false, nil
    if pc then okP, pawn = pcall(function() return pc:K2_GetPawn() end) end
    if not okP or not isValid(pawn) then return end
    deathHook.tries = deathHook.tries + 1
    local okHook, hookErr = pcall(RegisterHook, DEATH_HOOK, function(self)
        local okCall, err = pcall(function() onKill(self:get()) end)
        if not okCall then log("error counting a kill: " .. tostring(err)) end
    end)
    if okHook then
        deathHook.armed = true
        log("kill counting armed (try " .. deathHook.tries .. ")")
    elseif deathHook.tries == 1 or deathHook.tries % 12 == 0 then
        log("death hook not ready yet, will retry: " .. tostring(hookErr))
    end
end

-- Runs off the game thread; the work is queued onto it. Also keeps the pawn list fresh so a
-- respawned player still gets credit for creatures hit before dying
LoopAsync(5000, function()
    ExecuteInGameThread(function()
        armDeathHook()
        rememberMyPawn()
    end)
    return false
end)

