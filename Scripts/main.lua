local toast = { frame = nil, text = nil, shownId = 0 }

local function buildToast()
    local pc = localController()
    local lib = widgetLibrary()
    local panelClass = findClass("/Game/UI/Panels/WBP_Panel.WBP_Panel_C")
    local textClass = findClass("/Game/UI/Common/WBP_DomTextBlock.WBP_DomTextBlock_C") or findClass("/Script/UMG.TextBlock")
    if not (pc and lib and panelClass and textClass) then return false end
    local okF, frame = pcall(function() return lib:Create(pc, panelClass, pc) end)
    if not okF or not isValid(frame) then return false end
    local tree = frame.WidgetTree
    local canvas = newWidget("CanvasPanel", tree)
    local text = newText(tree, textClass, "", cfg.MessageFontSize, GOLD)
    if not (canvas and text) then return false end
    if not pcall(function() tree.RootWidget = canvas end) then return false end
    pcall(function() text:SetJustification(1) end)   -- 1 = Center
    local okS, slot = pcall(function() return canvas:AddChildToCanvas(text) end)
    if okS and slot then
        -- Centred, a little below the middle of the screen, above the hotbar
        pcall(function() slot:SetAnchors({ Minimum = { X = 0.5, Y = 0.72 }, Maximum = { X = 0.5, Y = 0.72 } }) end)
        pcall(function() slot:SetAlignment({ X = 0.5, Y = 0.5 }) end)
        pcall(function() slot:SetAutoSize(true) end)
        pcall(function() slot:SetPosition({ X = 0, Y = 0 }) end)
    end
    pcall(function() frame:SetVisibility(3) end)   -- 3 = HitTestInvisible
    if not pcall(function() frame:AddToViewport(850) end) then return false end
    toast.frame, toast.text = frame, text
    return true
end

local function showKillMessage(message)
    if not (isValid(toast.frame) and isValid(toast.text)) then
        toast.frame, toast.text = nil, nil
        if not buildToast() then
            if not toast.warned then
                toast.warned = true
                log("could not show kill messages on screen")
            end
            return
        end
    end
    pcall(function() toast.text:SetText(FText(message)) end)
    pcall(function() toast.frame:SetVisibility(3) end)
    -- Each message hides itself after MessageSeconds unless a newer one replaced it
    toast.shownId = toast.shownId + 1
    local id = toast.shownId
    ExecuteWithDelay(math.max(1, cfg.MessageSeconds) * 1000, function()
        ExecuteInGameThread(function()
            if toast.shownId == id and isValid(toast.frame) then
                pcall(function() toast.frame:SetVisibility(1) end)   -- 1 = Collapsed
            end
        end)
    end)
end

