-- NPC Kill Log - RuneScape: Dragonwilds
--
-- Counts every NPC you kill, per character, and shows the counts in a window:
--   Goblin Warrior: 55
--   Giant Rat: 94
--
-- How it works:
--   * Kills: the Blueprint event BP_DominionAICharacter_C:BP_OnDeath, which runs once for every
--     creature that dies (not on unload, not for the player). The hook can only be registered once
--     the Blueprint is loaded, so it is retried every few seconds until a world is up. A kill counts
--     when the local player's pawn is in the dead AI's damage list (its controller's
--     ThreatSystem.DamageInstigators), so kills made by other players in co-op are left out
--     (OnlyMyKills).
--     The first version used AiAttackTicketsManager:OnAiDeath(ai) with
--     AIAudioManagerComponent:HandleDeath(ai) as a backup; they are kept commented out below
--     in case this hook stops working. ProgressComponent:OnAIKilled looks like the obvious event
--     but is called straight from C++, so a Lua hook on it never runs (checked with a probe,
--     2026-09-28).
--   * Names: the killed character's AI data row name (AIDataTableRowHandle.RowName, read from the
--     character or its AI controller, whichever has it) and its class
--     name are looked up in the game's own AI name string tables (npc_names.lua, generated by
--     tools/gen_npc_names.py). names.txt can override any name.
--   * Saving: one plain text file per character next to the game's saves,
--     %LOCALAPPDATA%\RSDragonwilds\Saved\NpcKillLog-<name>-<id>.txt, one "Name: count" line per NPC.
--     It is rewritten a couple of seconds after each kill, so it is always readable by hand too.
--   * Window: the game's own framed panel (WBP_Panel) with a search box and a scrolling list.
--     Opened from an NPC KILL LOG entry added to the pause menu (Esc), or optionally a key
--     (OpenKey, off by default). The pause menu is resumed first, since the pause menu's
--     backdrop draws over any window added to the viewport while it is up.
--     Esc or its CLOSE button closes it.
--   * Controller: a pad's A presses CommonUI buttons from C++, so the click hook never sees it, and
--     a window in the viewport never gets pad focus. So the pause menu entry is made selectable
--     (A selects it, which a tick loop notices), and for a controller the kill log is docked inside
--     the open pause menu instead, with D-pad links from the entry into it and back. No search box
--     there (a pad cannot type); PREV PAGE / NEXT PAGE scroll the list. B closes the pause menu and
--     the panel with it.
--   * Kill message: after each kill a line of text shows for a few seconds, for example
--     "Your Goblin Warrior kill count is now: 5." (MessageSeconds). Bosses and other NPCs have
--     their own on/off switch (ShowBossKillMessages, ShowKillMessages), also flipped with the two
--     buttons in the window, which save to toggles.txt. A boss is anything the game gives a boss
--     health bar, anything built on the game's miniboss base classes, and anything with "Boss" in
--     its class name, plus ExtraBosses and minus NotBosses from config.txt.

local TAG = "[NpcKillLog] "
