local function localController()
    if isValid(state.pc) then return state.pc end
    local ok, all = pcall(FindAllOf, "PlayerController")
    if not ok or not all then return nil end
    for _, pc in ipairs(all) do
        local okL, isLocal = pcall(function() return pc:IsLocalController() end)
        if isValid(pc) and okL and isLocal then
            state.pc = pc
            return pc
        end
    end
    return nil
end

local function savedFolder()
    local base = os.getenv("LOCALAPPDATA")
    if base and base ~= "" then return base .. "\\RSDragonwilds\\Saved" end
    return nil
end

-- The game's own character save holds a unique id, so a new character that reuses a deleted
-- character's name does not inherit its counts
local function characterGuid(folder, name)
    local f = io.open(folder .. "\\SaveCharacters\\" .. name .. ".json", "r")
    if not f then return nil end
    local text = f:read("*a")
    f:close()
    return text and text:match('"char_guid"%s*:%s*"(%x+)"')
end

local function loadCounts(path)
    local counts = {}
    local f = io.open(path, "r")
    if not f then
        f = io.open(path .. ".tmp", "r")   -- a save that was interrupted between write and rename
        if not f then return counts end
    end
    for line in f:lines() do
        if line:sub(1, 1) ~= "#" then
            local name, n = line:match("^(.-):%s*(%d+)%s*$")
            if name and name ~= "" then counts[name] = (counts[name] or 0) + tonumber(n) end
        end
    end
    f:close()
    return counts
end

-- filter is already a lookupKey (lower case, letters and digits only), so "giant rat",
-- "Giant-Rat" and "giantrat" all find Giant Rat even if a space or dash does not reach the box
local function sortedEntries(filter)
    local list = {}
    for name, n in pairs(state.kills) do
        if not filter or lookupKey(name):find(filter, 1, true) then
            list[#list + 1] = { name = name, count = n }
        end
    end
    if cfg.SortBy == "name" then
        table.sort(list, function(a, b) return a.name:lower() < b.name:lower() end)
    else
        table.sort(list, function(a, b)
            if a.count ~= b.count then return a.count > b.count end
            return a.name:lower() < b.name:lower()
        end)
    end
    return list
end

local function saveNow()
    state.savePending = false
    if not state.file then return end
    local lines = { "# NPC Kill Log. One \"Name: count\" line per NPC." }
    local byName = {}
    for name, n in pairs(state.kills) do byName[#byName + 1] = { name = name, count = n } end
    table.sort(byName, function(a, b) return a.name:lower() < b.name:lower() end)
    for _, e in ipairs(byName) do lines[#lines + 1] = e.name .. ": " .. e.count end

    local tmp = state.file .. ".tmp"
    local f = io.open(tmp, "w")
    if not f then
        log("cannot write " .. tmp)
        return
    end
    f:write(table.concat(lines, "\n") .. "\n")
    f:close()
    -- Windows rename does not replace an existing file, so remove the old one first
    os.remove(state.file)
    local okRename, err = os.rename(tmp, state.file)
    if not okRename then log("cannot rename " .. tmp .. ": " .. tostring(err)) end
end

local function scheduleSave()
    if state.savePending then return end
    state.savePending = true
    ExecuteWithDelay(2000, function()
        ExecuteInGameThread(saveNow)
    end)
end

-- Works out which character is playing and loads its counts. Kills counted before the character
-- was known are kept and merged in.
local function ensureCharacter()
    local pc = localController()
    if not pc then return state.key ~= nil end
    local okN, name = pcall(function() return pc.PlayerState:GetPlayerName():ToString() end)
    if not okN or not name or name == "" then return state.key ~= nil end

    local folder = savedFolder()
    local guid = folder and characterGuid(folder, name)
    local safe = name:gsub("[^%w%-_]", "_")
    local key = safe .. (guid and ("-" .. guid:sub(1, 8)) or "")
    if key == state.key then return true end

    if state.key and state.savePending then saveNow() end
    local pending = (state.key == nil) and state.kills or {}
    state.key = key
    state.file = (folder or MOD_FOLDER) .. (folder and "\\" or "/") .. "NpcKillLog-" .. key .. ".txt"
    state.kills = loadCounts(state.file)
    local merged = 0
    for n, c in pairs(pending) do
        state.kills[n] = (state.kills[n] or 0) + c
        merged = merged + c
    end
    if merged > 0 then scheduleSave() end
    local types, total = 0, 0
    for _, c in pairs(state.kills) do types = types + 1; total = total + c end
    log("character " .. name .. ": " .. killSummary(total, types) .. " (" .. state.file .. ")")
    return true
end

