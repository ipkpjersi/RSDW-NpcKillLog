local classCache = {}
local function findClass(path)
    local c = classCache[path]
    if c and isValid(c) then return c end
    c = nil
    pcall(function() c = StaticFindObject(path) end)
    if not isValid(c) and path:sub(1, 6) == "/Game/" then
        -- Blueprint classes may need loading first: "/Game/X/WBP_Y.WBP_Y_C" -> load "/Game/X/WBP_Y"
        pcall(function() LoadAsset((path:gsub("%.[^%.]*$", ""))) end)
        pcall(function() c = StaticFindObject(path) end)
    end
    if not isValid(c) then return nil end
    classCache[path] = c
    return c
end

local function newWidget(className, tree)
    local c = findClass("/Script/UMG." .. className)
    if not c then return nil end
    local ok, w = pcall(StaticConstructObject, c, tree)
    return ok and w or nil
end

local function newText(tree, textClass, text, size, color)
    local ok, tb = pcall(StaticConstructObject, textClass, tree)
    if not ok or not tb then return nil end
    pcall(function()
        local font = tb.Font
        font.Size = size
        tb:SetFont(font)
    end)
    pcall(function() tb:SetColorAndOpacity({ SpecifiedColor = color, ColorUseRule = 0 }) end)
    pcall(function() tb:SetText(FText(text)) end)
    return tb
end

local function widgetLibrary()
    local lib = nil
    pcall(function() lib = StaticFindObject("/Script/UMG.Default__WidgetBlueprintLibrary") end)
    return isValid(lib) and lib or nil
end

local function setInputForWindow(on)
    if not cfg.CaptureMouse then return end
    local pc = localController()
    local lib = widgetLibrary()
    if not pc or not lib then return end
    pcall(function() pc.bShowMouseCursor = on end)
    if on then
        local focus = ui.search or ui.frame
        if not pcall(function() lib:SetInputMode_UIOnlyEx(pc, focus, 0, false) end) then
            pcall(function() lib:SetInputMode_GameAndUIEx(pc, focus, 0, false, false) end)
        end
    else
        pcall(function() lib:SetInputMode_GameOnly(pc, false) end)
    end
end

