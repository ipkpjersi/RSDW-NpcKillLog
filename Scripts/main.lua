local function showKillMessage(message)
    if not (isValid(toast.frame) and isValid(toast.text)) then
        toast.frame, toast.text = nil, nil
        if not buildToast() then
            if not toast.warned then
                toast.warned = true
                log("could not show kill messages on screen")
            end
            return
        end
    end
    pcall(function() toast.text:SetText(FText(message)) end)
    pcall(function() toast.frame:SetVisibility(3) end)
    -- Each message hides itself after MessageSeconds unless a newer one replaced it
    toast.shownId = toast.shownId + 1
    local id = toast.shownId
    ExecuteWithDelay(math.max(1, cfg.MessageSeconds) * 1000, function()
        ExecuteInGameThread(function()
            if toast.shownId == id and isValid(toast.frame) then
                pcall(function() toast.frame:SetVisibility(1) end)   -- 1 = Collapsed
            end
        end)
    end)
end

-- Scrolls a list by pages of its visible height (the window's by default)
