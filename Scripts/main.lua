-- The mod folder is the parent of the Scripts folder this file runs from
local function modFolder()
    local info = debug.getinfo(1, "S")
    local path = (info and info.source or ""):gsub("\\", "/")
    if path:sub(1, 1) == "@" then path = path:sub(2) end
    return path:match("^(.*)/Scripts/[^/]*$")
end

local function trim(s)
    return (s:match("^%s*(.-)%s*$"))
end

-- Calls fn(key, value) for every "Key = value" line of a text file; anything after # is a comment
local function readKeyValueFile(path, fn)
    local f = io.open(path, "r")
    if not f then return false end
    for raw in f:lines() do
        local text = trim((raw:gsub("#.*$", "")))
        local eq = text:find("=", 1, true)
        if eq then fn(trim(text:sub(1, eq - 1)), trim(text:sub(eq + 1))) end
    end
    f:close()
    return true
end

local function loadConfig(folder)
    local found = readKeyValueFile(folder .. "/config.txt", function(key, value)
        local default = cfg[key]
        if default == nil then
            log("unknown config key ignored: " .. key)
        elseif type(default) == "number" then
            local n = tonumber(value)
            if n then cfg[key] = math.floor(n) else log("not a number for " .. key .. ": " .. value) end
        elseif type(default) == "boolean" then
            local lower = value:lower()
            cfg[key] = (lower == "true" or lower == "yes" or lower == "1")
        else
            cfg[key] = value
        end
    end)
    if not found then log("no config.txt found, using defaults") end
end

