refreshWindow = function()
    if not ui.open or not isValid(ui.list) then return end
    local filter = nil
    if isValid(ui.search) then
        local okT, t = pcall(function() return ui.search:GetText():ToString() end)
        if okT and t and trim(t) ~= "" then filter = trim(t):lower() end
    end
    ui.lastFilter = filter or ""

    local entries = sortedEntries(filter and lookupKey(filter))
    local lines = {}
    for i, e in ipairs(entries) do lines[i] = e.name .. ": " .. formatCount(e.count) end
    local text
    if #lines > 0 then
        text = table.concat(lines, "\n")
    elseif filter then
        text = "No NPCs match \"" .. filter .. "\"."
    else
        text = "No kills yet. Go hunting."
    end
    pcall(function() ui.list:SetText(FText(text)) end)

    local types, total = 0, 0
    for _, c in pairs(state.kills) do types = types + 1; total = total + c end
    local head = killSummary(total, types)
    if filter then head = head .. "   |   showing " .. #entries end
    pcall(function() ui.header:SetText(FText(head)) end)
end

local function closeWindow()
    if not ui.open then return end
    ui.open = false
    if isValid(ui.frame) then pcall(function() ui.frame:SetVisibility(1) end) end   -- 1 = Collapsed
    setInputForWindow(false)
end

-- true while the pause menu is showing; nil when that cannot be told
local function pauseMenuShowing()
    local pm = menu.pm
    if not isValid(pm) then return false end
    local okA, active = pcall(function() return pm:IsActivated() end)
    if okA and type(active) == "boolean" then return active end
    local okV, visible = pcall(function() return pm:IsVisible() end)
    if okV and type(visible) == "boolean" then return visible end
    return nil
end

local function openWindow()
    if ui.open then return end
    ensureCharacter()
    if not isValid(ui.frame) or not isValid(ui.list) then
        ui.frame = nil
        if not buildWindow() then return end
    else
        pcall(function() ui.frame:SetVisibility(0) end)   -- 0 = Visible
    end
    ui.open = true
    refreshWindow()
    setInputForWindow(true)
    -- Watch the search box while the window is open; there is no text changed callback from Lua
    LoopAsync(250, function()
        if not ui.open then return true end
        ExecuteInGameThread(function()
            if not ui.open then return end
            if not isValid(ui.search) then return end
            local okT, t = pcall(function() return ui.search:GetText():ToString() end)
            local filter = (okT and t and trim(t):lower()) or ""
            if filter ~= ui.lastFilter then refreshWindow() end
        end)
        return false
    end)
end

