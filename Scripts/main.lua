local function isValid(obj)
    if obj == nil then return false end
    local ok, v = pcall(function() return obj:IsValid() end)
    return ok and v == true
end

-- FText, FString and FName values all have ToString in UE4SS
local function toText(v)
    if v == nil then return nil end
    if type(v) == "string" then return v end
    local ok, s = pcall(function() return v:ToString() end)
    if ok and type(s) == "string" then return s end
    return nil
end

local function formatCount(n)
    local s = tostring(math.floor(n))
    local out = s
    while true do
        local replaced, count = out:gsub("^(%d+)(%d%d%d)", "%1,%2")
        out = replaced
        if count == 0 then return out end
    end
end

-- "1,234 kills of 23 NPC types", with "kill" and "NPC type" when the count is 1
local function killSummary(total, types)
    return formatCount(total) .. (total == 1 and " kill" or " kills") .. " of "
        .. formatCount(types) .. (types == 1 and " NPC type" or " NPC types")
end

-- "GoblinRuntBoss(Thug)" -> "Goblin Runt Boss (Thug)", "Medium_Beast" -> "Medium Beast"
local function prettify(s)
    s = s:gsub("_", " ")
    s = s:gsub("(%l)(%u)", "%1 %2"):gsub("(%u)(%u%l)", "%1 %2")
    s = s:gsub("(%a)%(", "%1 ("):gsub("(%a)(%d)", "%1 %2")
    return trim((s:gsub("%s+", " ")))
end

