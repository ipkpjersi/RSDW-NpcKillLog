-- names.txt: "RowOrClassName = Shown Name" lines that win over everything else
local overrides = {}
readKeyValueFile(MOD_FOLDER .. "/names.txt", function(key, value)
    if key ~= "" and value ~= "" then overrides[lookupKey(key)] = value end
end)

local function shownName(key)
    if not key or key == "" or key == "None" then return nil end
    local k = lookupKey(key)
    return overrides[k] or displayByKey[k]
end

-- 'BP_AI_GiantRat_SW_Character_C' -> 'GiantRat_SW', 'BP_AI_Kebbit_Character_02_C' -> 'Kebbit'
-- (a numbered copy of a creature's blueprint is still the same creature)
local function classStem(className)
    local stem = className:gsub("_C$", ""):gsub("^BP_AI_", ""):gsub("^BP_", "")
    stem = stem:gsub("_%d+$", "")
    stem = stem:gsub("_Character$", "")
    return stem
end

local nameByClass = {}      -- class name -> resolved name, so each class is only worked out once
local loggedClasses = {}

-- The AI data row handle may live on the character or on its AI controller (the game binary lists
-- it among controller-looking properties), so try both; the first kill logs which one answered
local rowSourceLogged = false

local function rowNameOf(ai)
    local sources = { { "character", ai } }
    local ctrl = nil
    pcall(function() ctrl = ai.Controller end)
    if not isValid(ctrl) then pcall(function() ctrl = ai:GetController() end) end
    if isValid(ctrl) then sources[#sources + 1] = { "controller", ctrl } end
    for _, src in ipairs(sources) do
        local okR, rowName = pcall(function() return src[2].AIDataTableRowHandle.RowName:ToString() end)
        if okR and type(rowName) == "string" and rowName ~= "" and rowName ~= "None" then
            if not rowSourceLogged then
                rowSourceLogged = true
                log("AI data row names come from the " .. src[1])
            end
            return rowName
        end
    end
    if not rowSourceLogged then
        rowSourceLogged = true
        log("no AI data row name on the character or its controller (controller "
            .. (isValid(ctrl) and "found" or "not found") .. "); names come from class names")
    end
    return nil
end

local function resolveName(ai)
    local okC, className = pcall(function() return ai:GetClass():GetFName():ToString() end)
    className = okC and className or "Unknown"
    local rowName = rowNameOf(ai)

    local cacheKey = className .. "|" .. tostring(rowName)
    local cached = nameByClass[cacheKey]
    if cached then return cached end

    local stem = classStem(className)
    local name, how = nil, nil
    -- 1. an override or string table entry for the row name (or its known alias)
    if rowName then
        name = overrides[lookupKey(rowName)] or shownName(ROW_ALIASES[rowName] or rowName)
        how = name and "row " .. rowName
    end
    -- 2. the class name (or its known alias), whole ("HellHound_Minion_Fido") then without its last
    --    part, then its last part
    if not name then
        local tries = { ROW_ALIASES[stem] or stem, (stem:gsub("_[^_]*$", "")), stem:match("_([^_]+)$") }
        for _, t in ipairs(tries) do
            name = t and shownName(t)
            if name then how = "class " .. className; break end
        end
    end
    -- 3. a tidied up version of the row or class name
    if not name then
        name = prettify(rowName or stem)
        how = "fallback from " .. (rowName and ("row " .. rowName) or ("class " .. className))
    end

    nameByClass[cacheKey] = name
    if not loggedClasses[cacheKey] then
        loggedClasses[cacheKey] = true
        log("new NPC type: " .. className .. " (row " .. tostring(rowName) .. ") -> " .. name .. " [" .. how .. "]")
    end
    return name
end

