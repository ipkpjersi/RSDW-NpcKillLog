-- "F4", "K" or "CTRL+SHIFT+K" -> key, { modifiers }
local function parseKey(spec)
    local mods = {}
    local keyName = nil
    for part in spec:upper():gmatch("[^+%s]+") do
        if part == "CTRL" or part == "CONTROL" then mods[#mods + 1] = ModifierKey.CONTROL
        elseif part == "SHIFT" then mods[#mods + 1] = ModifierKey.SHIFT
        elseif part == "ALT" then mods[#mods + 1] = ModifierKey.ALT
        else keyName = part end
    end
    local key = keyName and Key[keyName]
    return key, mods
end

-- Closes the pause menu when it is up, then opens the window a moment later, once the menu and
-- its backdrop are gone and the game has handed back input. Opening on top of the pause menu leaves
-- the window behind the menu's backdrop and the game paused. fromMenu: the pause menu entry was
-- clicked, so the menu is up even when pauseMenuShowing cannot tell.
local function openAfterPauseMenu(fromMenu)
    local pm = menu.pm
    if isValid(pm) and (fromMenu or pauseMenuShowing()) then
        pcall(function() pm:Resume() end)
        ExecuteWithDelay(250, function() ExecuteInGameThread(openWindow) end)
    else
        openWindow()
    end
end

local function toggleWindow()
    ExecuteInGameThread(function()
        if ui.open then closeWindow() else openAfterPauseMenu() end
    end)
end

if cfg.OpenKey ~= "" then
    local openKey, openMods = parseKey(cfg.OpenKey)
    if not openKey then
        log("unknown OpenKey " .. cfg.OpenKey .. ", no key bound")
    elseif #openMods > 0 then
        RegisterKeyBind(openKey, openMods, toggleWindow)
    else
        RegisterKeyBind(openKey, toggleWindow)
    end
end

-- ---------------------------------------------------------------------------
-- Pause menu entry
-- ---------------------------------------------------------------------------
-- The pause menu (WBP_PauseMenuScreen_C) lists its entries as WBP_DomAllCapsButton_C buttons in
-- VerticalBox_PauseMenu. Our entry is one more button in that list, just above the two exits.

local EXIT_BUTTONS = { "ExitToMainMenuButton", "ExitToDesktopMenu" }

local function isRealPauseMenu(pm)
    if not isValid(pm) then return false end
    local okN, n = pcall(function() return pm:GetFName():ToString() end)
    return okN and type(n) == "string" and n:sub(1, 9) ~= "Default__"
end

local function findPauseMenu(allowSearch)
    if isRealPauseMenu(menu.pm) then return menu.pm end
    for i = #menu.seen, 1, -1 do
        if isRealPauseMenu(menu.seen[i]) then
            menu.pm = menu.seen[i]
            menu.seen = {}
            return menu.pm
        end
    end
    menu.seen = {}
    -- Last resort: a search of every object, slow (tens of ms), so at most every 10 seconds
    if allowSearch and os.clock() >= menu.nextSearch then
        menu.nextSearch = os.clock() + 10
        local ok, pm = pcall(FindFirstOf, "WBP_PauseMenuScreen_C")
        if ok and isRealPauseMenu(pm) then menu.pm = pm; return pm end
    end
    return nil
end

local function inBox(box, w)
    local ok, idx = pcall(function() return box:GetChildIndex(w) end)
    return ok and type(idx) == "number" and idx >= 0
end

-- A widget's vertical box slot settings as plain values, so they survive the widget leaving the box
local function slotLayout(w)
    local layout = nil
    pcall(function()
        local s = w.Slot
        local pad, size = s.Padding, s.Size
        layout = {
            padding = { Left = pad.Left, Top = pad.Top, Right = pad.Right, Bottom = pad.Bottom },
            size = { SizeRule = size.SizeRule, Value = size.Value },
            h = s.HorizontalAlignment,
            v = s.VerticalAlignment,
        }
    end)
    return layout
end

local function addToBox(box, w, layout)
    local okS, slot = pcall(function() return box:AddChildToVerticalBox(w) end)
    if not (okS and slot and layout) then return end
    pcall(function() slot:SetPadding(layout.padding) end)
    pcall(function() slot:SetSize(layout.size) end)
    pcall(function() slot:SetHorizontalAlignment(layout.h) end)
    pcall(function() slot:SetVerticalAlignment(layout.v) end)
end

hookButtonClicks = function()
    if menu.hooked then return end
    menu.hooked = true
    local ok, err = pcall(RegisterHook, "/Script/CommonUI.CommonButtonBase:HandleButtonClicked", function(self)
        local okA, addr = pcall(function() return self:get():GetAddress() end)
        if not okA or not addr then return end
        -- Only note the click here; the window is built on a later tick, outside the click handler
        if addr == menu.buttonAddr then
            ExecuteWithDelay(1, function() ExecuteInGameThread(function() openAfterPauseMenu(true) end) end)
        elseif ui.closeAddr and addr == ui.closeAddr then
            ExecuteWithDelay(1, function() ExecuteInGameThread(closeWindow) end)
        elseif ui.toggleAddrs and ui.toggleAddrs[addr] then
            local t = ui.toggleAddrs[addr]
            ExecuteWithDelay(1, function() ExecuteInGameThread(function() flipToggle(t) end) end)
        end
    end)
    if not ok then log("could not watch button clicks, the pause menu entry will not work: " .. tostring(err)) end
end

-- Makes sure our entry is in the pause menu. Cheap when it already is.
local function ensureMenuButton(allowSearch)
    if not cfg.ShowInPauseMenu then return end
    local pm = findPauseMenu(allowSearch)
    if not pm then return end
    local box = nil
    pcall(function() box = pm.VerticalBox_PauseMenu end)
    if not isValid(box) then return end
    if isValid(menu.button) and inBox(box, menu.button) then return end

    local b = newGameButton(localController(), cfg.MenuLabel)
    if not b then return end
    local settings = nil
    pcall(function() settings = pm.SettingsButton end)
    local ourLayout = isValid(settings) and slotLayout(settings) or nil

    -- Take the exits out, add our entry, put the exits back with their own spacing
    local exits = {}
    for _, name in ipairs(EXIT_BUTTONS) do
        local e = nil
        pcall(function() e = pm[name] end)
        if isValid(e) and inBox(box, e) then exits[#exits + 1] = { widget = e, layout = slotLayout(e) } end
    end
    for _, e in ipairs(exits) do pcall(function() box:RemoveChild(e.widget) end) end
    addToBox(box, b, ourLayout)
    for _, e in ipairs(exits) do addToBox(box, e.widget, e.layout) end

    menu.button = b
    pcall(function() menu.buttonAddr = b:GetAddress() end)
    hookButtonClicks()
    if not menu.announced then
        menu.announced = true
        log("added " .. cfg.MenuLabel .. " to the pause menu")
    end
end

-- The pause menu is created the first time Esc is pressed and its widgets a moment later, so
-- check a few times after it appears or Esc is pressed
local function scheduleMenuChecks()
    for i, delay in ipairs({ 100, 400, 1000, 2500 }) do
        ExecuteWithDelay(delay, function()
            ExecuteInGameThread(function() ensureMenuButton(i >= 3) end)
        end)
    end
end

